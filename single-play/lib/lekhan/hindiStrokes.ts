export function getLetterStrokes(id: string): LetterStrokes {
  return HINDI_STROKES[id] ?? HINDI_STROKES.a;
}

// Compose the strokes for a whole word from its letter ids, laying the letters
// out left-to-right (each letter re-placed in its own 0..100 slot). TraceSlate
// bbox-fits the result, so the child traces each letter in turn, stroke by
// stroke, across the wide word slate.
const WORD_ADVANCE = 92; // horizontal gap between successive letters

export function getWordStrokes(ids: string[]): LetterStrokes {
  const out: LetterStrokes = [];
  ids.forEach((id, i) => {
    const dx = i * WORD_ADVANCE;
    for (const stroke of getLetterStrokes(id)) {
      out.push(stroke.map(([x, y]) => [x + dx, y] as [number, number]));
    }
  });
  return out;
}
