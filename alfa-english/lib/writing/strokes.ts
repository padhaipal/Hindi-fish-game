// ---------------------------------------------------------------------------
// LETTER STROKES — ordered pen strokes for each lowercase letter.
// ---------------------------------------------------------------------------
// Each letter is an ORDERED list of strokes; each stroke is a polyline of
// [x, y] points in a 0..100 box (y increases DOWNWARD), listed in writing
// order — the FIRST point of each stroke is where the pen goes down.
//
// Reference lines used while authoring:
//   ascender top  ~12   (stems of b d f h k l t)
//   x-height top  ~42   (tops of the small round letters)
//   baseline      ~80
//   descender     ~98   (tails of g j p q y)
//   i / j dot     ~20
//
// The Writing game draws these as the guide and makes the child trace every
// stroke, in order, from its start — so e.g. t's crossbar is its own stroke and
// MUST be drawn. Curves are approximated by enough points to read smoothly.
// ---------------------------------------------------------------------------

