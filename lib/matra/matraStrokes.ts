// ---------------------------------------------------------------------------
// MATRA WRITING STROKES — for the matra writing activity.
// ---------------------------------------------------------------------------
// For each matra, the syllable "क + matra" is split into the CONSONANT strokes
// (क — drawn already in place) and the MATRA strokes (what the child writes),
// both as ordered polylines in a shared 0..100 box (y down). Derived from the
// medial axis of the rendered syllable: matra = syllable skeleton MINUS the
// consonant's ink, so each matra sits in its true position (right / left /
// above / below क).
// ---------------------------------------------------------------------------

