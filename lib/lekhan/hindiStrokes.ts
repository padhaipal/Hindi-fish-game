// ---------------------------------------------------------------------------
// HINDI LETTER STROKES — ordered pen strokes for each Devanagari letter.
// ---------------------------------------------------------------------------
// Each letter (keyed by its ASCII id, see lib/letters.ts) is an ORDERED list of
// strokes; each stroke is a polyline of [x, y] points in a 0..100 box (y grows
// DOWNWARD), listed in writing order — the FIRST point of each stroke is where
// the pen goes down (its red start dot). The child must trace every stroke, in
// order, from its start, so each distinctive part (the vertical डंडा, the top
// शिरोरेखा / head-line, matras, dots) is its own mandatory stroke.
//
// The letters used by this app are derived from the medial axis (skeleton) of
// the rendered Devanagari glyph, so the traced guide matches the printed letter;
// stroke order/segmentation follows the ALfA charts (body → डंडा → head-line).
// TraceSlate re-fits each letter's bounding box into the slate, so only the
// SHAPE matters, not absolute placement.
// ---------------------------------------------------------------------------

